"""修正pygoruut phonemizer對特定漢字的系統性發音錯誤。

## 背景

拿教育部TAT-MOE語料庫(86,000+句人工標註台羅發音)當ground truth，
大規模比對pygoruut對同一批句子的IPA輸出，發現25.2%音節有系統性發音
錯誤(完整分析見`reports/moe_corpus_taigi_analysis.md`)。大部分錯誤
是文白異讀(同一字有兩種合法讀音，系統選錯context)，這種**不適合**
用固定表覆蓋(會在另一個context把原本對的改錯)，所以這裡的收錄標準是
**「語料庫掃描到的錯誤樣本裡，正確答案永遠只有一種」**——不保證這個字
在所有可能語境下都無合法例外，但至少在這批3,000句真實語料裡沒出現過
反例。

**刻意排除數字類字元(一二三四五六九十百千萬億)**：就算掃描樣本裡只
顯示單一讀音，數字類字元有廣為人知的文白異讀模式(例如「一」在序數
vs計數context讀音不同)，這批3,000句剛好沒踩到不代表沒有例外，風險
比其他字類別更高，需要另外判斷語境的邏輯才能安全處理，不是這個模組
的範圍。

**刻意排除「純鼻音自成音節」字元(園/長/兩/算/黃等，讀音是hng/tng/nng/
sng/ng這種沒有母音的音節)**：開發過程實測發現pygoruut對這類字有時會
用特殊的鼻音聲調符號(ń/ǹ，帶重音符號)標記，不是這個模組假設的標準
Chao tone letter系統，貿然套用轉換規則算出來的IPA可能是模型詞彙表
根本沒有的符號組合，需要另外查證才能安全處理。

第一批(毋/我/的)人工逐一直接觀察pygoruut在已知正確語境下的輸出來
決定覆蓋值；後續擴充批次(2026-08-06)用程式化的台羅數字調->IPA轉換器
(`tailo_to_ipa.py`風格邏輯，開發時的一次性腳本，沒有留在repo裡)大量
產生，轉換規則已經用前15組人工驗證過的真實pygoruut輸出配對測試過
(子音/母音/鼻化/入聲尾/聲調全部通過)才拿來套用在其餘118個字元上。

## 運作方式

不是改pygoruut本身(它沒有暴露自訂發音詞庫的API，見開發過程紀錄)，
而是在phonemizer輸出IPA之後、送進TTS模型的tokenizer之前，用「輸入的
漢字」對齊「輸出的IPA音節」，把已知目標字元對應到的那一段IPA音節
原地替換掉——只替換該字元自己的音節span，不動其他部分(包含緊跟在
後面沒有聲調符號的雜訊字元，例如未被音素化的生僻字或標點)，避免像
「用parts重組整句」那樣不小心把trailing的東西弄丟。

**只在漢字數跟切出來的IPA音節數對得起來時才替換**(跟
`reports/moe_corpus_taigi_analysis.md`分析時同樣的保守原則)：對不
起來代表沒把握對齊是不是正確的，寧可不修，不要冒著改錯別的字的風險。

## 已知限制：對齊失敗時整句跳過，造成約7%的覆蓋率缺口

這個保守原則有一個量化過的代價：實測對「的」這個字(第一批118字表裡的
既有entry)在30,001個含「的」的語料庫句子上直接呼叫`apply_pronunciation_
overrides()`，發現漢字數跟IPA音節數對得起來的句子裡，override**100%
正確套用**(4,471/4,471，沒有例外)——但另外約7.2%的句子(348/4,819)因為
對不起來被整句跳過，override完全沒被嘗試，那些句子還是用pygoruut的
原始(可能錯誤的)輸出。這不是這個模組的邏輯bug，是設計上的保守取捨，
但這個缺口影響所有列在`CHARACTER_IPA_OVERRIDES`裡的字元，不只是
「的」——記錄下來避免以後誤以為override沒生效。

## 移除記錄(2026-09-10)：「共」被證實是真正的文白異讀字，不適合固定表

`scripts/crosscheck_overrides_against_benchmark.py`拿這學期做的母語者
盲測黃金標準(`ambiguity_gold_benchmark_v1/v2`)反查這張表，原本只是懷疑
「共」可能是文白異讀字(這張表自己的收錄原則本來就該排除這種字，見上面
docstring)，v2黃金標準擴充到40筆驗證資料後，**證實**了這個懷疑：
「感謝你共我鬥相共」驗證出kang7，「請你共我敲電話予護理師」驗證出
kheng7——兩個真實醫療語境的正確讀音不一樣，但這張表原本固定寫「共→ka7」，
跟兩者都不符，等於兩句都會念錯。已移除這個entry，不再假裝「共」只有
一種正確讀音。正式生產環境(`assistant_service`)實際上已經改用
`chhoetaigi_pronunciation_resolver.py`(不查這張表)，這裡移除主要是為了
不讓還在用`NeurlangTTSBackend`預設行為(`tw_hokkien_tts_pipeline/tts.py`)
的其他呼叫端(例如`pipeline.py`)繼續套用這個已證實錯誤的值。
"""

