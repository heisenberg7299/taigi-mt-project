_PUNCT_STRIP_RE = re.compile(r"[，。？！、；：「」『』（）—－,\.\?!;:\(\)　\s]")
# 音節本體(非聲調符號的部分)不能吃到標點——不然標點會被吸進音節span裡，
# 整段替換掉的時候連標點一起被吃掉(見開發過程實測到的bug：「你好，我」
# 的逗號因此消失)，這裡明確排除跟_PUNCT_STRIP_RE同一批標點字元
_TONE_SPAN_RE = re.compile(r"[^˥˦˧˨˩，。？！、；：「」『』（）—－,\.\?!;:\(\)　\s]+[˥˦˧˨˩]+")


def _hanji_chars_no_punct(text: str) -> list[str]:
    return list(_PUNCT_STRIP_RE.sub("", text))


def apply_pronunciation_overrides(
    hanji_text: str, ipa_output: str, overrides: dict[str, str] | None = None
) -> str:
    """`hanji_text`是送進phonemizer的原始漢字句子，`ipa_output`是
    phonemizer回傳的IPA字串。回傳修正後的IPA字串；如果字數/音節數對不
    齊(沒把握對齊)，原樣回傳不修改。

    `overrides`預設是這個模組的`CHARACTER_IPA_OVERRIDES`(教育部TAT-MOE
    語料庫統計出來的固定表)，向後相容既有行為；呼叫端可以傳入其他{字元:
    IPA}表(例如`chhoetaigi_pronunciation_resolver.py`用ChhoeTaigi辭典+
    黃金標準動態算出來的表)取代，兩者用的是同一套「比對字數/音節數,
    對得起來才替換」的對齊邏輯，不必重新實作一次。
    """
    if overrides is None:
        overrides = CHARACTER_IPA_OVERRIDES
    han_chars = _hanji_chars_no_punct(hanji_text)
    if not any(c in overrides for c in han_chars):
        return ipa_output  # 沒有目標字元，不用花時間比對，直接跳過

    spans = [m.span() for m in _TONE_SPAN_RE.finditer(ipa_output)]
    if len(spans) != len(han_chars):
        return ipa_output  # 對不齊，寧可不修，見module docstring

    pieces = []
    cursor = 0
    for char, (start, end) in zip(han_chars, spans):
        pieces.append(ipa_output[cursor:start])
        if char in overrides:
            pieces.append(overrides[char])
        else:
            pieces.append(ipa_output[start:end])
        cursor = end
    pieces.append(ipa_output[cursor:])
    return "".join(pieces)
