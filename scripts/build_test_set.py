CATEGORIES = [
    ("daily", "一般生活", DAILY, None),
    ("medical", "醫療需求", MEDICAL, None),
    ("robot_service", "機器人服務", ROBOT, None),
    ("negation_risk", "否定與風險", NEGATION, "negation"),
    ("numbers_id", "數字人名病房號", NUMBERS, "number_consistency"),
    ("code_mixing", "中英台混合", CODEMIX, "code_mixing"),
]


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    rows = []
    counters = {}
    for cat_id, cat_name, sentences, check_type in CATEGORIES:
        counters[cat_id] = 0
        for zh in sentences:
            counters[cat_id] += 1
            rows.append({
                "id": f"{cat_id}_{counters[cat_id]:03d}",
                "zh": zh,
                "category": cat_id,
                "category_zh": cat_name,
                "check_type": check_type,
                "nan_han": None,
                "tailo": None,
                "source": "manual_test_set",
                "verified": False,
            })
    with open(OUT, "w") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"寫入 {len(rows)} 句到 {OUT}")
    for cat_id, cat_name, sentences, _ in CATEGORIES:
        print(f"  {cat_name}({cat_id}): {len(sentences)}")


if __name__ == "__main__":
    main()
